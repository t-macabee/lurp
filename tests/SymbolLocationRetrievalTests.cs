    [Fact]
    public async Task Navigate_ReturnsLineNumbers()
    {
        var snapshotId = await SeedAndIndexAsync();
        var widgetId = ResolveSymbolId(snapshotId, SymbolFqn);

        using var store = OpenStore(DbPath);
        var loc = Assert.Single(store.GetDeclarationLocations(widgetId, snapshotId));
        var lineToNavigate = loc.StartLine;

        var result = RunCaptured(() => NavigateHandler.Run(new[]
        {
            "--mode=navigate",
            $"--file={Document}",
            $"--line={lineToNavigate}",
            $"--output-dir={TestDir}"
        }));

        Assert.Null(result.Failure);

        using var doc = JsonDocument.Parse(result.Stdout);
        var root = doc.RootElement;
        var target = root.GetProperty("target");

        Assert.Equal(lineToNavigate, target.GetProperty("start_line").GetInt32());
        Assert.Equal(loc.EndLine, target.GetProperty("end_line").GetInt32());
        Assert.Equal(Document, target.GetProperty("document_path").GetString());
    }

    [Fact]
    public async Task Navigate_RoundTrip_ThroughLine_ReturnsSameSymbol()
    {
        var snapshotId = await SeedAndIndexAsync();
        var widgetId = ResolveSymbolId(snapshotId, SymbolFqn);

        string reportedStartLine;
        using (var store = OpenStore(DbPath))
        {
            var loc = Assert.Single(store.GetDeclarationLocations(widgetId, snapshotId));
            reportedStartLine = loc.StartLine.ToString(System.Globalization.CultureInfo.InvariantCulture);
        }

        var result = RunCaptured(() => NavigateHandler.Run(new[]
        {
            "--mode=navigate",
            $"--file={Document}",
            $"--line={reportedStartLine}",
            $"--output-dir={TestDir}"
        }));

        Assert.Null(result.Failure);

        using var doc = JsonDocument.Parse(result.Stdout);
        var target = doc.RootElement.GetProperty("target");
        Assert.Equal(widgetId, target.GetProperty("symbol_id").GetString());
        Assert.Equal(Document, target.GetProperty("document_path").GetString());
    }
}