    private static void AssertSplitLocations(JsonElement root)
    {
        Assert.Equal(2, root.GetProperty("declaration_count").GetInt32());
        var locations = root.GetProperty("locations").EnumerateArray().ToList();
        Assert.Equal(2, locations.Count);
        Assert.Equal(SplitUserDoc, locations[0].GetProperty("document_path").GetString());
