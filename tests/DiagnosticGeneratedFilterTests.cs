using Lurp.Storage;
using Microsoft.Data.Sqlite;
using System.Text;

namespace Lurp.Tests;

public sealed class DiagnosticGeneratedFilterTests : IDisposable
{
    private readonly string _dbPath;
    private readonly string _gitRoot;
    private readonly SqliteIndexStore _store;
    private const string SnapshotId = "diag-gen-snap-1";

    public DiagnosticGeneratedFilterTests()
    {
        _gitRoot = Path.Combine(Path.GetTempPath(), $"lurp_diaggen_{Guid.NewGuid():N}");
        Directory.CreateDirectory(_gitRoot);
        _dbPath = Path.Combine(_gitRoot, "index.db");
        _store = new SqliteIndexStore(_dbPath);
        _store.Open();
        _store.RunMigrations();
        Seed();
    }

    public void Dispose()
    {
        _store.Close();
        TestDatabase.DeleteDirectory(_gitRoot);
        GC.SuppressFinalize(this);
    }

    private void Seed()
    {
        using var conn = TestDatabase.Open(_dbPath);
        using (var pragma = conn.CreateCommand())
        {
            pragma.CommandText = "PRAGMA foreign_keys=OFF;";
            pragma.ExecuteNonQuery();
        }

        using (var cmd = conn.CreateCommand())
        {
            cmd.CommandText = """
                INSERT INTO workspaces (workspace_id, git_root, solution_path)
                VALUES ('ws1', @gitRoot, @solutionPath);

                INSERT INTO snapshots (snapshot_id, workspace_id, built_at_utc, sdk_version, database_schema_version, output_schema_version, status)
                VALUES (@sid, 'ws1', '2026-01-01T00:00:00.0000000Z', '10.0.100', 44, 6, 'complete');
                """;
            cmd.Parameters.AddWithValue("@gitRoot", _gitRoot);
            cmd.Parameters.AddWithValue("@solutionPath", Path.Combine(_gitRoot, "Test.slnx"));
            cmd.Parameters.AddWithValue("@sid", SnapshotId);
            cmd.ExecuteNonQuery();
        }

        InsertDoc(conn, "src/A.cs", "public class A { }\n", "doc-a", "ver-a", isGenerated: false);
        InsertDoc(conn, "src/Hdr.cs", "// <auto-generated/>\npublic class Hdr { }\n", "doc-hdr", "ver-hdr", isGenerated: true);

        InsertDiag(conn, Path.Combine(_gitRoot, "src", "A.cs"), "CS0168", "diag in A");
        InsertDiag(conn, Path.Combine(_gitRoot, "src", "Hdr.cs"), "CS0168", "diag in Hdr");
        InsertDiag(conn, Path.Combine(_gitRoot, "obj", "Debug", "net10.0", "A.AssemblyInfo.cs"), "CS0168", "diag in obj");
        InsertDiag(conn, Path.Combine(_gitRoot, "src", "Gone.cs"), "CS0168", "diag in Gone");
    }

    private static void InsertDoc(SqliteConnection conn, string relPath, string content, string docId, string versionId, bool isGenerated)
    {
        var bytes = Encoding.UTF8.GetBytes(content);
        var hash = Convert.ToHexString(System.Security.Cryptography.SHA256.HashData(bytes));
        var lineStarts = LineBreaks.ComputeLineStartsJson(bytes);
        using var cmd1 = conn.CreateCommand();
        cmd1.CommandText = "INSERT INTO documents (document_id, relative_path) VALUES (@did, @path);";
        cmd1.Parameters.AddWithValue("@did", docId);
        cmd1.Parameters.AddWithValue("@path", relPath);
        cmd1.ExecuteNonQuery();

        using var cmd2 = conn.CreateCommand();
        cmd2.CommandText = """
            INSERT INTO document_versions (document_version_id, document_id, content_hash, content, encoding, byte_count, line_starts, is_generated)
            VALUES (@vid, @did, @hash, @content, 'utf-8', @bc, @ls, @gen);
            """;
        cmd2.Parameters.AddWithValue("@vid", versionId);
        cmd2.Parameters.AddWithValue("@did", docId);
        cmd2.Parameters.AddWithValue("@hash", hash);
        cmd2.Parameters.AddWithValue("@content", bytes);
        cmd2.Parameters.AddWithValue("@bc", bytes.Length);
        cmd2.Parameters.AddWithValue("@ls", lineStarts);
        cmd2.Parameters.AddWithValue("@gen", isGenerated ? 1 : 0);
        cmd2.ExecuteNonQuery();

        using var cmd3 = conn.CreateCommand();
        cmd3.CommandText = "INSERT INTO snapshot_documents (snapshot_id, document_version_id) VALUES (@sid, @vid);";
        cmd3.Parameters.AddWithValue("@sid", SnapshotId);
        cmd3.Parameters.AddWithValue("@vid", versionId);
        cmd3.ExecuteNonQuery();
    }

    private static void InsertDiag(SqliteConnection conn, string fullPath, string id, string message)
    {
        using var cmd = conn.CreateCommand();
        cmd.CommandText = """
            INSERT INTO diagnostics (snapshot_id, project_name, document_path, severity, id, message, start_line, start_column, end_line, end_column)
            VALUES (@sid, 'App', @path, 'Warning', @id, @msg, 1, 0, 1, 5);
            """;
        cmd.Parameters.AddWithValue("@sid", SnapshotId);
        cmd.Parameters.AddWithValue("@path", fullPath);
        cmd.Parameters.AddWithValue("@id", id);
        cmd.Parameters.AddWithValue("@msg", message);
        cmd.ExecuteNonQuery();
    }

    [Fact]
    public void DefaultView_HidesGeneratedAndBuildOutputDiagnostics()
    {
        var defaultPage = _store.GetDiagnosticsPage(
            SnapshotId, projectName: null, documentPath: null, severity: null,
            excludeHidden: true, id: null, limit: 50, cursor: null, includeGenerated: false);

        var defaultPaths = defaultPage.Items.Select(i => i.NormalizedDocumentPath).OrderBy(p => p, StringComparer.Ordinal).ToList();
        Assert.Equal(["src/A.cs", "src/Gone.cs"], defaultPaths);

        var allPage = _store.GetDiagnosticsPage(
            SnapshotId, projectName: null, documentPath: null, severity: null,
            excludeHidden: true, id: null, limit: 50, cursor: null, includeGenerated: true);

        var allPaths = allPage.Items.Select(i => i.NormalizedDocumentPath).OrderBy(p => p, StringComparer.Ordinal).ToList();
        Assert.Equal(
            ["obj/Debug/net10.0/A.AssemblyInfo.cs", "src/A.cs", "src/Gone.cs", "src/Hdr.cs"],
            allPaths);
    }
}
